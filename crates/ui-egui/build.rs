//! Embeds the translation catalogs and the interface faces.
//!
//! StudioCraft's own catalogs are in this crate, in `i18n/locales/<locale>/studiocraft.tsv`
//! (craft-i18n's catalog format). The `en` folder lists the English source rows and is not
//! embedded. The shared catalogs come from the craft-i18n checkout named by `CRAFT_I18N_DIR`:
//!
//! - Unset or empty: every locale in this crate's `i18n/locales` is embedded with its
//!   `studiocraft.tsv` alone.
//! - Set: every locale with a `studiocraft.tsv` here or in the checkout's `locales/<locale>/` is
//!   embedded with the checkout's `common.tsv`, and so is the locale its region falls back to (`pt`
//!   for `pt-br`). When both have a `studiocraft.tsv`, their rows are merged, and a row in this
//!   crate replaces the checkout's row with the same context and source text.
//! - `CRAFT_I18N_REQUIRED=1` (release builds): a missing or unreadable checkout stops the build.
//!
//! The locales with a `studiocraft.tsv` are the ones the Language setting offers.
//!
//! Fonts come from the craft-fonts checkout named by `CRAFT_FONTS_DIR`:
//!
//! - Unset or empty: the table is empty, and the window uses the faces in `assets/fonts`
//!   followed by egui's built-in fonts.
//! - Set: every selected face in the checkout's `fonts/manifest.txt` is built into the app, and
//!   the CJK interface faces are cut to the characters of the embedded catalogs.
//! - `CRAFT_FONTS_REQUIRED=1` (release builds): a missing or unreadable checkout stops the build.
//!
//! Only local directories are read.

use std::collections::{BTreeMap, HashSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// The app's catalog file in each locale folder.
const APP_CATALOG: &str = "studiocraft.tsv";
/// The catalog the Craft apps share, in each locale folder.
const SHARED_CATALOG: &str = "common.tsv";
/// StudioCraft's own locale folders, relative to this crate.
const TREE_LOCALES: &str = "i18n/locales";
/// The largest catalog file read, in bytes.
const MAX_CATALOG: u64 = 8 * 1024 * 1024;

fn main() {
    println!("cargo::rerun-if-changed=build.rs");
    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_default());
    let catalogs = match translations(&out_dir) {
        Ok(c) => c,
        Err(e) => {
            println!("cargo::error={e}");
            Catalogs::default()
        }
    };
    let out = out_dir.join("craft_i18n.rs");
    if let Err(e) = std::fs::write(&out, catalogs.source()) {
        println!("cargo::error=writing {}: {e}", out.display());
    }
    if let Err(e) = craft_fonts_build::Embed::new().subset_to(catalogs.files()).write("craft_fonts.rs") {
        println!("cargo::error={e}");
    }
}

/// One embedded locale: its code and the paths of its two catalogs, when present.
struct Locale {
    code: String,
    shared: Option<String>,
    app: Option<String>,
}

#[derive(Default)]
struct Catalogs {
    locales: Vec<Locale>,
}

impl Catalogs {
    /// The generated Rust: `CRAFT_I18N` and `APP_LOCALES`.
    fn source(&self) -> String {
        let mut o = String::from("// Generated by the build script from i18n/locales and CRAFT_I18N_DIR. Do not edit.\n");
        let include = |path: &Option<String>| path.as_ref().map_or_else(|| "\"\"".to_string(), |p| format!("include_str!({p:?})"));
        o.push_str("/// The embedded catalogs: (locale, shared catalog, StudioCraft's catalog).\n");
        o.push_str("pub static CRAFT_I18N: &craft_i18n::Embedded = &[\n");
        for l in &self.locales {
            let _ = writeln!(o, "    ({:?}, {}, {}),", l.code, include(&l.shared), include(&l.app));
        }
        o.push_str("];\n");
        let offered: Vec<&str> = self.locales.iter().filter(|l| l.app.is_some()).map(|l| l.code.as_str()).collect();
        o.push_str("/// The locales with a StudioCraft catalog.\n");
        let _ = writeln!(o, "pub static APP_LOCALES: &[&str] = &{offered:?};");
        o
    }

    /// Every embedded catalog file, for the interface fonts.
    fn files(&self) -> Vec<PathBuf> {
        self.locales.iter().flat_map(|l| [&l.shared, &l.app]).flatten().map(PathBuf::from).collect()
    }
}

/// The catalog files of one locale folder of the checkout.
#[derive(Default)]
struct Found {
    shared: Option<PathBuf>,
    app: Option<PathBuf>,
}

/// The catalogs to embed, with the merged app catalogs written under `out_dir`, or why they can't
/// be built.
fn translations(out_dir: &Path) -> Result<Catalogs, String> {
    println!("cargo::rerun-if-env-changed=CRAFT_I18N_DIR");
    println!("cargo::rerun-if-env-changed=CRAFT_I18N_REQUIRED");
    let required = std::env::var("CRAFT_I18N_REQUIRED").is_ok_and(|v| v.trim() == "1");
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default());
    let tree = tree_locales(&manifest.join(TREE_LOCALES))?;
    let checkout = match std::env::var_os("CRAFT_I18N_DIR").filter(|d| !d.is_empty()) {
        None if required => {
            return Err("CRAFT_I18N_REQUIRED=1 but CRAFT_I18N_DIR is unset: a release must embed the translations".into());
        }
        None => BTreeMap::new(),
        Some(dir) => match checkout_locales(&PathBuf::from(dir)) {
            Ok(c) => c,
            Err(e) if required => return Err(format!("CRAFT_I18N_DIR: {e}")),
            Err(e) => {
                println!("cargo::warning=CRAFT_I18N_DIR: {e}; only StudioCraft's own catalogs are built in");
                BTreeMap::new()
            }
        },
    };
    combine(&tree, &checkout, out_dir)
}

/// The locales to embed from this crate's catalogs (`tree`) and the checkout's (`checkout`), both
/// keyed by lowercase code. The app catalogs are written, merged, under `out_dir`.
fn combine(tree: &BTreeMap<String, PathBuf>, checkout: &BTreeMap<String, Found>, out_dir: &Path) -> Result<Catalogs, String> {
    let offered: Vec<&String> = tree.keys().chain(checkout.iter().filter(|(_, f)| f.app.is_some()).map(|(c, _)| c)).collect();
    let mut codes: Vec<&String> = tree.keys().chain(checkout.keys()).collect();
    codes.sort();
    codes.dedup();
    let mut locales = Vec::new();
    for code in codes {
        if !offered.iter().any(|o| *o == code || is_region_of(o, code)) {
            continue;
        }
        let found = checkout.get(code);
        let ours = tree.get(code).map(|p| read_catalog(p)).transpose()?;
        let theirs = found.and_then(|f| f.app.as_ref()).map(|p| read_catalog(p)).transpose()?;
        let app = if ours.is_none() && theirs.is_none() {
            None
        } else {
            let dir = out_dir.join("i18n").join(code);
            std::fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            let path = dir.join(APP_CATALOG);
            let text = merge(ours.as_deref().unwrap_or(""), theirs.as_deref().unwrap_or(""));
            std::fs::write(&path, text).map_err(|e| format!("writing {}: {e}", path.display()))?;
            Some(utf8(&path)?)
        };
        let shared = found.and_then(|f| f.shared.as_ref()).map(|p| utf8(p)).transpose()?;
        locales.push(Locale { code: code.clone(), shared, app });
    }
    Ok(Catalogs { locales })
}

/// The rows of `ours`, then every row of `theirs` whose context and source text `ours` doesn't
/// define. Comments and blank lines are left out.
fn merge(ours: &str, theirs: &str) -> String {
    let key = |line: &str| {
        let mut columns = line.splitn(3, '\t');
        Some((columns.next()?.to_string(), columns.next()?.to_string()))
    };
    let rows = |text: &str| -> Vec<String> {
        let text = text.strip_prefix('\u{feff}').unwrap_or(text);
        text.split('\n').map(|l| l.strip_suffix('\r').unwrap_or(l).to_string()).filter(|l| !l.is_empty() && !l.starts_with('#')).collect()
    };
    let mine = rows(ours);
    let defined: HashSet<(String, String)> = mine.iter().filter_map(|l| key(l)).collect();
    let others = rows(theirs);
    let mut out = String::new();
    for line in mine.iter().chain(others.iter().filter(|l| key(l).is_none_or(|k| !defined.contains(&k)))) {
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// A catalog's text; it must be UTF-8 and at most [`MAX_CATALOG`] bytes.
fn read_catalog(path: &Path) -> Result<String, String> {
    println!("cargo::rerun-if-changed={}", path.display());
    let size = std::fs::metadata(path).map_err(|e| format!("{}: {e}", path.display()))?.len();
    if size > MAX_CATALOG {
        return Err(format!("{} is {size} bytes; a catalog may be at most {MAX_CATALOG}", path.display()));
    }
    std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))
}

/// `path` as a string for `include_str!`.
fn utf8(path: &Path) -> Result<String, String> {
    path.to_str().map(str::to_string).ok_or_else(|| format!("{} is not a UTF-8 path", path.display()))
}

/// Whether `code` is `parent` with a region subtag (two letters or three digits) after it.
fn is_region_of(code: &str, parent: &str) -> bool {
    code.strip_prefix(parent).and_then(|rest| rest.strip_prefix('-')).is_some_and(|region| {
        (region.len() == 2 && region.chars().all(|c| c.is_ascii_alphabetic())) || (region.len() == 3 && region.chars().all(|c| c.is_ascii_digit()))
    })
}

/// The locale folders of `locales`, by lowercase code, without `en` and `pseudo`.
fn locale_dirs(locales: &Path) -> Result<BTreeMap<String, PathBuf>, String> {
    let mut dirs = BTreeMap::new();
    for e in std::fs::read_dir(locales).map_err(|e| format!("{}: {e}", locales.display()))?.filter_map(Result::ok) {
        let path = e.path();
        if !path.is_dir() {
            continue;
        }
        let Some(code) = e.file_name().to_str().map(str::to_ascii_lowercase) else {
            println!("cargo::warning={} is not a UTF-8 name and is not embedded", path.display());
            continue;
        };
        if code == "en" || code == "pseudo" {
            continue;
        }
        if dirs.insert(code.clone(), path).is_some() {
            return Err(format!("{}: the locale {code} is there twice, in different cases", locales.display()));
        }
    }
    Ok(dirs)
}

/// This crate's catalogs: the `studiocraft.tsv` of each locale folder under `locales`.
fn tree_locales(locales: &Path) -> Result<BTreeMap<String, PathBuf>, String> {
    println!("cargo::rerun-if-changed={}", locales.display());
    let dirs = locale_dirs(locales)?;
    Ok(dirs.into_iter().map(|(code, dir)| (code, dir.join(APP_CATALOG))).filter(|(_, p)| p.is_file()).collect())
}

/// The catalogs of the checkout at `dir`, by lowercase code.
fn checkout_locales(dir: &Path) -> Result<BTreeMap<String, Found>, String> {
    // `include_str!` resolves a relative path against the generated file, and can't read a
    // canonical Windows path (`\\?\C:\…`), so the path is used as given and must be absolute.
    if !dir.is_absolute() {
        return Err(format!("{} is not an absolute path", dir.display()));
    }
    let locales = dir.join("locales");
    if !locales.is_dir() {
        println!("cargo::rerun-if-changed={}", dir.display());
        return Err(format!("{} has no locales/ folder", dir.display()));
    }
    println!("cargo::rerun-if-changed={}", locales.display());
    let file = |dir: &Path, name: &str| -> Option<PathBuf> {
        let path = dir.join(name);
        if !path.is_file() {
            return None;
        }
        println!("cargo::rerun-if-changed={}", path.display());
        if path.to_str().is_none() {
            println!("cargo::warning=CRAFT_I18N_DIR: {} is not a UTF-8 path and is not embedded", path.display());
            return None;
        }
        Some(path)
    };
    Ok(locale_dirs(&locales)?.into_iter().map(|(code, d)| (code, Found { shared: file(&d, SHARED_CATALOG), app: file(&d, APP_CATALOG) })).collect())
}
